import { z } from "zod";
import { getCreativeContext, saveCreative } from "@/lib/db/creatives";
import { renderCreative, toCreativeJpeg } from "@/lib/creative/render";
import { fail, ok } from "@/lib/http";

export const runtime = "nodejs";
export const maxDuration = 60;
const RenderRequest = z.object({ imageBase64: z.string().min(1).max(14_000_000).optional() });

export async function POST(request: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  if (!z.string().uuid().safeParse(id).success) return fail("VALIDATION", "Invalid variant ID", 400);
  if (Number(request.headers.get("content-length")) > 14_100_000) return fail("VALIDATION", "Image exceeds request limit", 413);
  let body: z.infer<typeof RenderRequest>;
  try { body = RenderRequest.parse(await request.json()); }
  catch { return fail("VALIDATION", "Expected JSON with optional imageBase64", 400); }
  try {
    const context = await getCreativeContext(id);
    if (!context) return fail("NOT_FOUND", "Variant not found", 404);
    let jpeg: Buffer;
    try {
      jpeg = await toCreativeJpeg(body.imageBase64 ?? Buffer.from(await renderCreative(context.brand, context.variant).arrayBuffer()));
    } catch { return fail("INVALID_IMAGE", "Unable to decode or render image", 422); }
    // Mock mode previews actual generated bytes without claiming a persistent upload.
    if (process.env.NEXT_PUBLIC_USE_MOCKS === "true") return ok({ imageUrl: `data:image/jpeg;base64,${jpeg.toString("base64")}` });
    return ok({ imageUrl: await saveCreative(id, jpeg) });
  } catch { return fail("CREATIVE_FAILED", "Unable to save creative", 500); }
}
